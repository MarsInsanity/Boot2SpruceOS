#!/usr/bin/env python3
# The app's icon from spruce's tree (spruceOS spruce/imgs/tree_sm_close_crop.png, 88x152 pixel art),
# traced to straight edges. It matches that image pixel for pixel but one stray pixel. TreePath.java
# draws the same outline in the app.
#
#   tools/make-icons.py     (re)writes res/drawable/ic_launcher_foreground.xml, the adaptive icon's
#                           foreground and monochrome layer, and res/mipmap-*/ic_launcher.png, the
#                           icons Android 5-7.1 use. Needs Pillow.
import os

from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BG = (0x28, 0x28, 0x28)    # spruce theme background #282828
TREE = (0xFB, 0xF1, 0xC7)  # spruce theme highlight #FBF1C7

# Tree units: 88 wide, 152.5 tall.
W, H = 88, 152.5
CANOPY = [(40, 0), (88, 48), (79, 57), (48, 26), (40, 34), (88, 82), (79.5, 90.5), (48.5, 59.5),
          (40.5, 67.5), (88, 115), (88, 116), (79.5, 124.5), (48.5, 93.5), (17.5, 124.5), (0, 107),
          (17, 90), (0.5, 73.5), (17.5, 56.5), (0.5, 39.5)]
TRUNK = [(40, 118.5), (57, 118.5), (57, 152.5), (40, 152.5)]

# Adaptive icon: a 108 dp canvas, of which a 72 dp circle or squircle shows, and only a 66 dp circle is
# safe from every launcher's mask. The tree is 48 dp tall (its corners stay 6 dp inside that circle),
# the Material size for an icon's artwork.
ICON_DP, TREE_DP = 108, 48


def fmt(v):
    return ("%.4f" % v).rstrip("0").rstrip(".")


def path_data():
    out = []
    for poly in (CANOPY, TRUNK):
        out.append("M" + " L".join("%s,%s" % (fmt(x), fmt(y)) for x, y in poly) + " Z")
    return " ".join(out)


def vector():
    s = TREE_DP / H
    tx, ty = (ICON_DP - W * s) / 2, (ICON_DP - TREE_DP) / 2
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make-icons.py: spruce's tree, 48 dp tall on the 108 dp adaptive icon canvas.
     Also the monochrome layer (Android 13+ themed icons), which only uses its shape. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{ICON_DP}dp"
    android:height="{ICON_DP}dp"
    android:viewportWidth="{ICON_DP}"
    android:viewportHeight="{ICON_DP}">
    <group
        android:translateX="{fmt(tx)}"
        android:translateY="{fmt(ty)}"
        android:scaleX="{fmt(s)}"
        android:scaleY="{fmt(s)}">
        <path
            android:fillColor="#FBF1C7"
            android:pathData="{path_data()}" />
    </group>
</vector>
"""


def legacy_png(px):
    # Android 7.1 (the RG552's own Android) and older have no adaptive icons: a spruce-grey circle,
    # the tree in the same proportion to it as on the adaptive icon's 72 dp visible circle.
    k = 8
    big = px * k
    im = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    m = big * 0.04
    d.ellipse((m, m, big - m, big - m), fill=BG + (255,))
    s = (big - 2 * m) * TREE_DP / 72 / H
    ox, oy = (big - W * s) / 2, (big - H * s) / 2
    for poly in (CANOPY, TRUNK):
        d.polygon([(ox + x * s, oy + y * s) for x, y in poly], fill=TREE + (255,))
    return im.resize((px, px), Image.LANCZOS)


if __name__ == "__main__":
    with open(os.path.join(HERE, "res/drawable/ic_launcher_foreground.xml"), "w") as f:
        f.write(vector())
    for dens, px in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
        os.makedirs(os.path.join(HERE, f"res/mipmap-{dens}"), exist_ok=True)
        legacy_png(px).save(os.path.join(HERE, f"res/mipmap-{dens}/ic_launcher.png"), optimize=True)
    print(path_data())
